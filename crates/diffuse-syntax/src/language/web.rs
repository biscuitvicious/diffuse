//! TypeScript / JavaScript / JSX / MJS language profiles (one shared profile).

use regex::Regex;

use crate::profile::{BlockDelimStyle, LangProfile};

pub const KEYWORDS: &[&str] = &[
    "as",
    "async",
    "await",
    "break",
    "case",
    "catch",
    "class",
    "const",
    "continue",
    "debugger",
    "default",
    "delete",
    "do",
    "else",
    "enum",
    "export",
    "extends",
    "false",
    "finally",
    "for",
    "from",
    "function",
    "get",
    "if",
    "import",
    "in",
    "instanceof",
    "interface",
    "let",
    "new",
    "null",
    "of",
    "return",
    "set",
    "static",
    "super",
    "switch",
    "this",
    "throw",
    "true",
    "try",
    "typeof",
    "var",
    "void",
    "while",
    "with",
    "yield",
];

pub const OPERATORS: &[&str] = &[
    "!=", "!==", "%=", "&&", "&&=", "&=", "**", "**=", "*=", "++", "+=", "--", "-=", "->", "/=",
    "<<", "<<=", "<=", "==", "===", "=>", ">=", ">>", ">>=", ">>>", ">>>=", "??", "??=", "^=",
    "|=", "||", "||=",
];

pub fn profile() -> LangProfile {
    LangProfile {
        name: "web",
        keywords: KEYWORDS,
        line_comment: true,
        block_comment: true,
        types_by_case: true,
        hash_comment: false,
        fence: None,
        unlabeled_fence_lang: None,
        fence_strip: None,
        markdown: false,
        block_style: BlockDelimStyle::Braces,
        fn_decl: Some(
            Regex::new(r"^\s*(?:export\s+)?(?:default\s+)?(?:async\s+)?function\s+([A-Za-z0-9_]+)")
                .expect("ts fn_decl"),
        ),
        decl_prefixes: &[
            "function ",
            "async function ",
            "class ",
            "interface ",
            "type ",
            "enum ",
            "const ",
            "let ",
            "var ",
            "export ",
            "export default ",
            "export async function ",
            "export class ",
            "export interface ",
            "export type ",
            "export enum ",
            "export const ",
            "export let ",
        ],
        operators: OPERATORS,
        scope_stop_prefixes: &[
            "class ",
            "interface ",
            "type ",
            "enum ",
            "export class ",
            "export interface ",
            "export type ",
            "export enum ",
        ],
        exact_delimiters: BlockDelimStyle::Braces.default_exact_delimiters(),
        tail_delimiters: BlockDelimStyle::Braces.default_tail_delimiters(),
        trailing_delimiters: BlockDelimStyle::Braces.default_trailing_delimiters(),
        property_syntax: crate::profile::PropertySyntax::Colon,
    }
}
