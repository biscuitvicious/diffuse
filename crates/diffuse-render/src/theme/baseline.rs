impl Baseline {
    /// Legacy `token_color` arm resolution: Mod/Mov rows resolve the ctx
    /// arm, matching the flat palette dispatch.
    pub(crate) fn token_color(&self, token: TokenColor, kind: RowKind) -> Option<Color> {
        let kind_idx = match kind {
            RowKind::Add => 1,
            RowKind::Del => 2,
            RowKind::Ctx | RowKind::Mod | RowKind::Mov => 0,
            // File/Sep rows never carry syntax tokens; the legacy dispatch
            // resolved them through the context arm.
            _ => 0,
        };
        let token_idx = TOKEN_KEYS
            .iter()
            .position(|(_, known)| *known == token)
            .expect("equivalence suite iterates TOKEN_KEYS");
        self.tokens[kind_idx][token_idx]
    }
}

